-- Add test progress tacking
ALTER TABLE user_progress
ADD COLUMN last_test_after_sequence_number INTEGER
NOT NULL DEFAULT 0
CONSTRAINT chk_last_test_sequence
CHECK (last_test_after_sequence_number >= 0);

--Create tests table
CREATE TABLE tests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY ,
    from_sequence_number INTEGER NOT NULL,
    to_sequence_number INTEGER NOT NULL,
    title VARCHAR(100) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_tests_to_sequence_number
                   UNIQUE (to_sequence_number),
    CONSTRAINT chk_tests_sequence_range
                   CHECK (
                       from_sequence_number >= 1
                        AND to_sequence_number = from_sequence_number + 5
                       ),
    CONSTRAINT fk_tests_from_word
                   FOREIGN KEY (from_sequence_number)
                   REFERENCES words (sequence_number),
    CONSTRAINT fk_tests_to_word
        FOREIGN KEY (to_sequence_number)
            REFERENCES words (sequence_number)
);

CREATE TABLE test_exercises (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    test_id BIGINT NOT NULL,
    exercise_type VARCHAR(30) NOT NULL,
    instruction TEXT NOT NULL,
    content TEXT NOT NULL,
    sort_order INTEGER NOT NULL,
    CONSTRAINT chk_test_exercises_sort_order
    CHECK (sort_order > 0),
    CONSTRAINT uq_test_exercises_order
        UNIQUE (test_id, sort_order),

    CONSTRAINT fk_test_exercises_test
        FOREIGN KEY (test_id)
        REFERENCES tests (id)
        ON DELETE CASCADE
);